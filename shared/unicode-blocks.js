  // 不做图形渲染、或属于代理/控制字符的码点，扫描时默认跳过
  function isRenderable(cp) {
    if (cp >= 0xD800 && cp <= 0xDFFF) return false;      // 代理对
    if (cp >= 0x0000 && cp <= 0x001F) return false;      // C0 控制
    if (cp === 0x007F) return false;

    if (cp >= 0x0080 && cp <= 0x009F) return false;      // C1 控制
    if (cp === 0xFEFF) return false;                     // BOM / 零宽不换行
    if (cp >= 0x200B && cp <= 0x200F) return false;      // 零宽字符 / 方向标记
    if (cp >= 0x2028 && cp <= 0x202E) return false;      // 分隔/方向控制
    if (cp >= 0x2060 && cp <= 0x2064) return false;      // 单词连接符等
    if (cp >= 0x2066 && cp <= 0x206F) return false;      // 方向隔离控制
    if (cp >= 0xFFF9 && cp <= 0xFFFB) return false;      // 注释标记
    if (cp >= 0xE0000 && cp <= 0xE007F) return false;    // Tags（除语言标签外多为控制）
    return true;
  }

